export function initSeedCards() {
  const existing = JSON.parse(localStorage.getItem('chua_cards') || '[]') as { id: string }[]
  const existingIds = new Set(existing.map(c => c.id))
  const toAdd = SEED_CARDS.filter(c => !existingIds.has(c.id))
  if (toAdd.length === 0) return
  toAdd.forEach(c => saveCard(c as any))
}
